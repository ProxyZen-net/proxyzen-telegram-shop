def lang_for(code: str | None) -> str:
    """Язык нового пользователя. Сохраняется в базе, дальше — только выбор пользователя."""
    default = os.environ.get("DEFAULT_LANG", "en").strip().lower()
    if default in ("en", "ru"):
        return default
